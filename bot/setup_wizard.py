"""First-run setup wizard with a simple GUI.

When no .env file is found (e.g. friend just double-clicked the .exe),
this wizard pops up asking for API keys and basic settings, then writes
a .env file so the bot can start.

Falls back to terminal prompts if no display is available (headless server).
"""

import os
import sys
from pathlib import Path


def _get_env_path() -> Path:
    if getattr(sys, "frozen", False):
        return Path(sys.executable).parent / ".env"
    from bot import config
    return config.PROJECT_ROOT / ".env"


def _needs_setup() -> bool:
    env_path = _get_env_path()
    if not env_path.exists():
        return True
    text = env_path.read_text()
    return "your_binance_api_key_here" in text or "BINANCE_API_KEY=" not in text


